namespace {

std::string hexRva(uint64_t value) {
    std::ostringstream oss;
    oss << "0x" << std::uppercase << std::hex << value;
    return oss.str();
}

std::string hexOffset(uint32_t value) {
    std::ostringstream oss;
    oss << "0x" << std::uppercase << std::hex << value;
    return oss.str();
}

void writeJson(const DumpResult& dump, const std::filesystem::path& path) {
    std::ofstream out(path);
    out << "{\n";
    out << "  \"game\": \"" << jsonEscape(dump.game) << "\",\n";
    out << "  \"module\": \"" << jsonEscape(dump.module) << "\",\n";
    out << "  \"version\": \"" << jsonEscape(dump.version) << "\",\n";
    out << "  \"sha256\": \"" << jsonEscape(dump.sha256) << "\",\n";
    out << "  \"timestamp\": \"" << jsonEscape(dump.timestamp) << "\",\n";

    out << "  \"globals\": {\n";
    bool first = true;
    for (const ManagerResult& manager : dump.validation.managers) {
        if (!manager.valid) {
            continue;
        }
        if (!first) out << ",\n";
        first = false;
        out << "    \"" << jsonEscape(manager.name) << "\": \"" << hexRva(manager.resolve.rva) << "\"";
    }
    out << "\n  },\n";

    out << "  \"globals_runtime\": {\n";
    first = true;
    for (const ManagerResult& manager : dump.validation.managers) {
        if (!manager.valid) {
            continue;
        }
        if (!first) out << ",\n";
        first = false;
        out << "    \"" << jsonEscape(manager.name) << "\": \"" << hexRva(manager.resolve.dereferenced) << "\"";
    }
    out << "\n  },\n";

    out << "  \"viewdata\": {\n";
    out << "    \"base\": \"" << hexRva(dump.validation.viewData.baseAddress) << "\",\n";
    out << "    \"CameraPosition\": \"" << hexOffset(0x190) << "\",\n";
    out << "    \"ViewProjection\": \"" << hexOffset(0x250) << "\",\n";
    out << "    \"AnchorPattern\": \"" << hexOffset(0x2A4) << "\"\n";
    out << "  },\n";

    out << "  \"structs\": {\n";
    out << "    \"GameManager_EntityList\": \"" << hexOffset(0xC8) << "\",\n";
    out << "    \"GameManager_EntityCount\": \"" << hexOffset(0xD0) << "\",\n";
    out << "    \"Entity_Position\": \"" << hexOffset(0x30) << "\",\n";
    out << "    \"Entity_Health\": \"" << hexOffset(0x118) << "\",\n";
    out << "    \"Entity_TeamId\": \"" << hexOffset(0x138) << "\",\n";
    out << "    \"Entity_NamePtr\": \"" << hexOffset(0x60) << "\",\n";
    out << "    \"Entity_BoneComponent\": \"" << hexOffset(0xA8) << "\"\n";
    out << "  },\n";

    out << "  \"validation\": {\n";
    out << "    \"viewDataValid\": " << (dump.validation.viewDataValid ? "true" : "false") << ",\n";
    out << "    \"entitiesValid\": " << (dump.validation.entitiesValid ? "true" : "false") << ",\n";
    out << "    \"entityCount\": " << dump.validation.entities.entityCount << ",\n";
    out << "    \"failures\": [";
    for (size_t i = 0; i < dump.validation.failures.size(); ++i) {
        if (i > 0) out << ", ";
        out << "\"" << jsonEscape(dump.validation.failures[i]) << "\"";
    }
    out << "]\n";
    out << "  }\n";
    out << "}\n";
}

void writeHeader(const DumpResult& dump, const std::filesystem::path& path) {
    std::ofstream out(path);
    out << "#pragma once\n\n";
    out << "#include <cstdint>\n\n";
    out << "// Generated by denimR6-dumper\n";
    out << "// Game: " << dump.game << "\n";
    out << "// Version: " << dump.version << "\n";
    out << "// SHA256: " << dump.sha256 << "\n";
    out << "// Timestamp: " << dump.timestamp << "\n\n";
    out << "struct Offsets {\n";

    for (const ManagerResult& manager : dump.validation.managers) {
        if (!manager.valid) {
            continue;
        }
        out << "    static inline constexpr uint64_t " << manager.name << " = "
            << hexRva(manager.resolve.rva) << ";\n";
    }

    out << "\n    // ViewData struct members (base found at runtime via heap scan)\n";
    out << "    static inline constexpr uint32_t ViewData_CameraPosition = 0x190;\n";
    out << "    static inline constexpr uint32_t ViewData_ViewProjection = 0x250;\n";
    out << "    static inline constexpr uint32_t ViewData_AnchorPattern = 0x2A4;\n\n";

    out << "    // Entity struct members (semi-static — update structs/offsets.json on patch)\n";
    out << "    static inline constexpr uint32_t GameManager_EntityList = 0xC8;\n";
    out << "    static inline constexpr uint32_t GameManager_EntityCount = 0xD0;\n";
    out << "    static inline constexpr uint32_t Entity_Position = 0x30;\n";
    out << "    static inline constexpr uint32_t Entity_Health = 0x118;\n";
    out << "    static inline constexpr uint32_t Entity_TeamId = 0x138;\n";
    out << "    static inline constexpr uint32_t Entity_NamePtr = 0x60;\n";
    out << "    static inline constexpr uint32_t Entity_BoneComponent = 0xA8;\n";
    out << "};\n";
}

} // namespace

bool exportDump(const DumpResult& dump, const std::string& outputDir) {
    std::error_code ec;
    std::filesystem::create_directories(outputDir, ec);

    const auto jsonPath = std::filesystem::path(outputDir) / "offsets.json";
    const auto headerPath = std::filesystem::path(outputDir) / "offsets.h";

    writeJson(dump, jsonPath);
    writeHeader(dump, headerPath);

    return std::filesystem::exists(jsonPath) && std::filesystem::exists(headerPath);
}
